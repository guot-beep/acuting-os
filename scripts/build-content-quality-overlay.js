#!/usr/bin/env node
/**
 * build-content-quality-overlay.js
 *
 * 兩軸 maturity(SOL 2026-08-12 建議,Fable 實作):
 *
 *   完整度  SKELETON / PARTIAL / FULL_DETAIL   ← 既有,回答「欄位齊了嗎」
 *   內容品質 UNREVIEWED / CLEAN / MINOR / DEFECT / SAFETY_HOLD  ← 本檔,回答「可信嗎」
 *
 * 92 張 full_detail 條件卡的人工 eyes-on 判定結果本來只存在 docs 的表格裡,
 * 機器讀不到,所以 UI 無法對 SAFETY 卡降級。這支把那些表格轉成一份 overlay。
 *
 * **刻意做成 overlay 而不是加欄位到卡片上**:schema 正規化目前是 PAUSE,
 * 而且品質判定是「對卡片的觀察」不是「卡片的內容」,混進卡片會讓兩者無法分辨,
 * 之後也難以重新產生。這份檔案可以整個刪掉再跑一次生出來。
 *
 * 判定來源是 ledger 的兩種表格,兩種都要讀:
 *   逐卡表  | 14 | `cond.breech_presentation` | **DEFECT（SAFETY）** | 理由 |
 *   處置表  | F-01 breech_presentation（SAFETY） | **RELOCATED**（…仍 OPEN…） |
 *
 * 為什麼處置表不能省:F-01 的血已經止了(污染內容搬走),但 BL67 處方重建仍 OPEN
 * —— 卡片現在仍然把合谷＋三陰交當成胎位不正的處方。只看逐卡表會以為已修完,
 * 只看處置表會以為沒事。兩張表都讀,才知道「當時發現什麼」與「現在還剩什麼」。
 */
const fs = require("fs");
const path = require("path");

const PACKS = path.join(__dirname, "..", "docs", "research_packs");
const OUT = path.join(__dirname, "..", "data", "quality", "content_quality.json");
const LEDGERS = fs
  .readdirSync(PACKS)
  .filter((f) => /^COND_FULLDETAIL_EYESON_\d+\.md$/.test(f))
  .sort();

const VERDICT = {
  "DEFECT（SAFETY）": "SAFETY_HOLD",
  DEFECT: "DEFECT",
  MINOR: "MINOR",
  CLEAN: "CLEAN",
};

const records = {};
const dispositions = [];

for (const file of LEDGERS) {
  const lines = fs.readFileSync(path.join(PACKS, file), "utf8").split("\n");
  lines.forEach((line, i) => {
    const card = line.match(/^\|\s*\d+\s*\|\s*`(cond\.[a-z0-9_]+)`\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|/);
    if (card) {
      const verdict = VERDICT[card[2].replace(/\*/g, "").trim()];
      if (!verdict) return;
      const prev = records[card[1]];
      const rank = ["CLEAN", "MINOR", "DEFECT", "SAFETY_HOLD"];
      // 同一張卡若被兩批審過,取較嚴重的判定 —— 較寬鬆的那次不會讓問題消失。
      if (!prev || rank.indexOf(verdict) > rank.indexOf(prev.quality)) {
        records[card[1]] = { quality: verdict, reason: card[3], evidence: `${file}:${i + 1}` };
      }
      return;
    }
    const disp = line.match(/^\|\s*(F-\d+)\s+([^|]+?)\s*\|\s*([^|]+?)\s*\|/);
    if (disp) {
      const status = disp[3].replace(/\*/g, "");
      dispositions.push({
        finding: disp[1],
        subject: disp[2],
        status: /^FIXED/.test(status) ? "FIXED" : /^RELOCATED/.test(status) ? "RELOCATED" : "OPEN",
        still_open: /OPEN/.test(status),
        detail: status,
        safety: /（SAFETY）|\(SAFETY\)/.test(disp[2]),
        evidence: `${file}:${i + 1}`,
      });
    }
  });
}

// 逐卡表記的是「審查當下」的判定,處置表記的是「後來修了沒」。只用逐卡表,
// 已經修好的卡會永遠掛著缺陷標籤 —— cond.bells_palsy 的 F-05 標著 FIXED,
// 卻仍被判 DEFECT。標籤在修好的卡上亮起,下次真的有缺陷時就沒人看了。
// 規則:某張卡對應的處置全部 FIXED → 降級為 REPAIRED(不上畫面);
//       只要還有一項 OPEN/RELOCATED-仍有 OPEN → 維持原判定。
for (const [id, rec] of Object.entries(records)) {
  const slug = id.replace(/^cond\./, "");
  const mine = dispositions.filter((d) => new RegExp(`\\b${slug}\\b`).test(d.subject));
  if (!mine.length) continue;
  rec.dispositions = mine.map((d) => `${d.finding}:${d.status}${d.still_open ? "(仍有 OPEN)" : ""}`);
  if (mine.every((d) => d.status === "FIXED" && !d.still_open)) {
    rec.audit_verdict = rec.quality;
    rec.quality = "REPAIRED";
  }
}

const counts = {};
for (const r of Object.values(records)) counts[r.quality] = (counts[r.quality] || 0) + 1;

const openSafety = dispositions.filter((d) => d.safety && d.still_open);

const out = {
  _comment:
    "Generated by scripts/build-content-quality-overlay.js from the eyes-on ledgers. " +
    "Do not hand-edit — re-run the script. Quality is an observation ABOUT a card, " +
    "not a field OF a card, which is why it lives here and not in the card schema.",
  generated_from: LEDGERS,
  axis: ["UNREVIEWED", "CLEAN", "MINOR", "DEFECT", "SAFETY_HOLD", "REPAIRED"],
  default: "UNREVIEWED",
  counts,
  records,
  safety_dispositions: dispositions.filter((d) => d.safety),
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n", "utf8");

console.log(`ledgers: ${LEDGERS.join(", ")}`);
console.log(`cards judged: ${Object.keys(records).length}`);
for (const k of ["CLEAN", "MINOR", "DEFECT", "SAFETY_HOLD", "REPAIRED"]) console.log(`  ${k.padEnd(12)}${counts[k] || 0}`);
console.log(`safety findings: ${dispositions.filter((d) => d.safety).length}  其中仍有 OPEN 項: ${openSafety.length}`);
for (const d of openSafety) console.log(`    ${d.finding} ${d.subject}`);
console.log(`\nwrote ${path.relative(path.join(__dirname, ".."), OUT).replace(/\\/g, "/")}`);
