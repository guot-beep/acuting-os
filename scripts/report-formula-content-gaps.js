const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const FORMULAS_PATH = path.join(ROOT, "data", "herbs", "formulas.json");
const OUTPUT_PATH = path.join(ROOT, "docs", "FORMULA_CONTENT_FILL_QUEUE.md");

const write = process.argv.includes("--write");
const data = JSON.parse(fs.readFileSync(FORMULAS_PATH, "utf8"));
const records = Array.isArray(data.records) ? data.records : [];

const classicalFields = [
  ["composition", (record) => record.composition],
  ["actions_en", (record) => record.actions_en],
  ["pattern_indications_en", (record) => record.pattern_indications_en],
  ["modifications_en", (record) => record.modifications_en],
  ["contraindications_en", (record) => record.contraindications_en],
  ["safety_flags", (record) => record.safety_flags],
  ["source_urls", (record) => record.source_urls],
  ["english_exam_track.actions", (record) => record.english_exam_track?.actions],
  ["english_exam_track.indications", (record) => record.english_exam_track?.indications],
  ["english_exam_track.modifications", (record) => record.english_exam_track?.modifications],
  ["english_exam_track.contraindications", (record) => record.english_exam_track?.contraindications]
];

function isEmpty(value) {
  if (Array.isArray(value)) return value.length === 0;
  if (typeof value === "string") return value.trim() === "";
  return value == null;
}

function collectDamagedStrings(value, output = []) {
  if (typeof value === "string" && (/^\?{2,}$/.test(value) || /\?{3,}/.test(value))) {
    output.push(value);
  } else if (Array.isArray(value)) {
    value.forEach((item) => collectDamagedStrings(item, output));
  } else if (value && typeof value === "object") {
    Object.values(value).forEach((item) => collectDamagedStrings(item, output));
  }
  return output;
}

function missingFields(record) {
  return classicalFields
    .filter(([, getter]) => isEmpty(getter(record)))
    .map(([name]) => name);
}

const skeletons = records.filter(
  (record) => record.source_type === "formula_canon_shortlist_skeleton"
);
const populated = records.filter(
  (record) => record.source_type !== "formula_canon_shortlist_skeleton"
);

if (records.length !== 115 || skeletons.length !== 92 || populated.length !== 23) {
  throw new Error(
    `Unexpected formula scope: ${records.length} total / ${populated.length} populated / ${skeletons.length} skeletons`
  );
}

const sortedSkeletons = [...skeletons].sort((a, b) =>
  `${a.category}\u0000${a.pinyin}`.localeCompare(`${b.category}\u0000${b.pinyin}`, "en")
);
const batchSizes = [30, 30, 32];
const batches = [];
let offset = 0;
for (let index = 0; index < batchSizes.length; index += 1) {
  const batchRecords = sortedSkeletons.slice(offset, offset + batchSizes[index]);
  batches.push({ id: `C2.${index + 1}`, records: batchRecords });
  offset += batchSizes[index];
}

const damagedPopulated = populated
  .map((record) => ({ id: record.id, count: collectDamagedStrings(record).length }))
  .filter((item) => item.count > 0);
const totalDamagedStrings = damagedPopulated.reduce((sum, item) => sum + item.count, 0);

const lines = [
  "# Formula Content Fill Queue",
  "",
  "Generated by `scripts/report-formula-content-gaps.js --write` from `data/herbs/formulas.json`.",
  "This is a read-only C2 planning report. It does not fill, repair, or promote formula content.",
  "",
  "## Safety Boundary",
  "",
  "- C2 fills classical study fields only: composition, actions, pattern indications, modifications, contraindications, and safety/source evidence.",
  "- Keep all new content `draft`; never promote to `source_checked` without approved textbook/source review.",
  "- Do not fill modern-use or condition links as part of these batches.",
  "- Existing question-mark damage is frozen encoding/content-repair work, not an empty-field gap. Do not overwrite it through C2.",
  "- Dose fields are outside C2 and require the separate dose-evidence staging and approval path.",
  "",
  "## Summary",
  "",
  `- formula records: ${records.length}`,
  `- populated pilot records: ${populated.length}`,
  `- skeleton records awaiting classical content: ${skeletons.length}`,
  `- deterministic fill batches: ${batches.map((batch) => batch.records.length).join(" / ")}`,
  `- populated records carrying frozen question-mark damage: ${damagedPopulated.length}`,
  `- damaged string values detected in populated records: ${totalDamagedStrings}`,
  "",
  "## Required Preview Workflow",
  "",
  "1. Create a staging file for one batch; do not edit `formulas.json` directly.",
  "2. Populate only fields listed as missing, with field-level sources and `review_status: draft`.",
  "3. Run a dry-run merge that refuses conflicts and refuses overwriting non-empty values.",
  "4. Show the diff summary to Ting/Claude before applying a batch.",
  "5. Apply only after approval, rebuild generated data, and run the standard validators.",
  ""
];

for (const batch of batches) {
  lines.push(`## ${batch.id} (${batch.records.length} formulas)`, "");
  lines.push("| Formula ID | Name | Category | Missing classical fields | Safety review prompt |", "| --- | --- | --- | ---: | --- |");
  for (const record of batch.records) {
    const missing = missingFields(record);
    const safetyPrompt = /emergency|toxic|professional|pregnan|bleed|anticoag/i.test(
      `${record.source_hint} ${record.name_en}`
    )
      ? "priority"
      : "standard";
    lines.push(
      `| \`${record.id}\` | ${record.name_zh} / ${record.name_en} | ${record.category} | ${missing.length} | ${safetyPrompt} |`
    );
  }
  lines.push("");
}

lines.push(
  "## Frozen Existing Damage",
  "",
  "These populated records contain question-mark damage. They remain outside C2 and require source-aware repair under the encoding/content-repair gate.",
  "",
  "| Formula ID | Damaged string values |",
  "| --- | ---: |"
);
for (const item of damagedPopulated) {
  lines.push(`| \`${item.id}\` | ${item.count} |`);
}
lines.push("");

const report = `${lines.join("\n")}\n`;
if (write) {
  fs.writeFileSync(OUTPUT_PATH, report, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)}`);
}
console.log(
  JSON.stringify(
    {
      formulas: records.length,
      populated: populated.length,
      skeletons: skeletons.length,
      batches: batches.map((batch) => batch.records.length),
      populated_with_frozen_damage: damagedPopulated.length,
      frozen_damaged_strings: totalDamagedStrings
    },
    null,
    2
  )
);
