const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const INPUT = path.join(ROOT, "data", "acupoints", "361.json");
const JSON_OUTPUT = path.join(ROOT, "data", "imports", "acupoint_sources", "gap_inventory.json");
const MD_OUTPUT = path.join(ROOT, "docs", "ACUPOINT_CONTENT_GAP_REPORT.md");

const points = JSON.parse(fs.readFileSync(INPUT, "utf8"));

function empty(value) {
  if (value == null || value === "") return true;
  if (Array.isArray(value)) return value.length === 0;
  if (typeof value === "object") return Object.keys(value).length === 0;
  return false;
}

function text(value) {
  if (value == null) return "";
  return typeof value === "string" ? value : JSON.stringify(value);
}

const checks = [
  { id: "location_zh", priority: "P0", lane: "WHO_GBT_LOCATION", missing: (p) => empty(p.location_zh) },
  { id: "location_en", priority: "P0", lane: "WHO_LOCATION", missing: (p) => empty(p.location_en) },
  { id: "functions_zh", priority: "P0", lane: "TEXTBOOK_TRADITIONAL", missing: (p) => empty(p.functions_zh) },
  { id: "functions_en", priority: "P0", lane: "TEXTBOOK_EXAM", missing: (p) => empty(p.functions_en) },
  { id: "indications_zh", priority: "P0", lane: "TEXTBOOK_TRADITIONAL", missing: (p) => empty(p.indications_zh) },
  { id: "indications_en", priority: "P0", lane: "TEXTBOOK_EXAM", missing: (p) => empty(p.indications_en) },
  { id: "needling", priority: "P0", lane: "TEXTBOOK_SAFETY", missing: (p) => empty(p.needling) },
  { id: "contraindications", priority: "P0", lane: "TEXTBOOK_SAFETY", missing: (p) => empty(p.contraindications) },
  { id: "sources", priority: "P1", lane: "SOURCE_TRACEABILITY", missing: (p) => empty(p.sources) },
  { id: "moxibustion_signal", priority: "P1", lane: "TEXTBOOK_MOXA", missing: (p) => !/(?:moxa|moxibustion|\u7078)/i.test([p.needling, p.contraindications, p.danger].map(text).join(" ")) },
  { id: "cun_measurement", priority: "P1", lane: "WHO_GBT_LOCATION", missing: (p) => empty(p.cun_measurement) },
  { id: "anatomy_terms", priority: "P1", lane: "WHO_ANATOMY_REVIEW", missing: (p) => empty(p.anatomy_terms) },
  { id: "muscles", priority: "P1", lane: "ANATOMY_TEXTBOOK", missing: (p) => empty(p.muscles) },
  { id: "bones", priority: "P1", lane: "ANATOMY_TEXTBOOK", missing: (p) => empty(p.bones) },
  { id: "nerves", priority: "P1", lane: "ANATOMY_TEXTBOOK", missing: (p) => empty(p.nerves) },
  { id: "vessels", priority: "P1", lane: "ANATOMY_TEXTBOOK", missing: (p) => empty(p.vessels) },
  { id: "nccaom_high_yield", priority: "P2", lane: "TING_NOTES_EXAM", missing: (p) => empty(p.nccaom_high_yield) },
  { id: "clinical_pearls", priority: "P2", lane: "TING_NOTES_CLINICAL", missing: (p) => empty(p.clinical_pearls) },
  { id: "evidence", priority: "P3", lane: "CONDITION_LEVEL_EVIDENCE", missing: (p) => empty(p.evidence) }
];

const findings = checks.map((check) => {
  const codes = points.filter(check.missing).map((point) => point.code);
  return {
    field: check.id,
    priority: check.priority,
    source_lane: check.lane,
    missing_count: codes.length,
    present_count: points.length - codes.length,
    missing_codes: codes
  };
});

const inventory = {
  generated_at: new Date().toISOString(),
  canonical_input: "data/acupoints/361.json",
  canonical_writes: 0,
  records_checked: points.length,
  rules: [
    "This inventory reports empty fields only; it does not certify existing content.",
    "A missing moxibustion signal means no explicit moxa wording was found, not that moxa is indicated.",
    "Evidence belongs at condition/intervention level unless a source explicitly supports a point-specific statement.",
    "No source lane may promote content beyond draft without field-level review."
  ],
  findings
};

fs.mkdirSync(path.dirname(JSON_OUTPUT), { recursive: true });
fs.writeFileSync(JSON_OUTPUT, `${JSON.stringify(inventory, null, 2)}\n`, "utf8");

const rows = findings
  .map((item) => `| ${item.priority} | \`${item.field}\` | ${item.present_count} | ${item.missing_count} | \`${item.source_lane}\` |`)
  .join("\n");

const coreComplete = findings
  .filter((item) => item.priority === "P0")
  .every((item) => item.missing_count === 0);

const markdown = `# Acupoint Content Gap Report

Generated by \`scripts/report-acupoint-content-gaps.js\` from the canonical 361-point file. This is a read-only inventory: canonical writes = **0**.

## Executive Summary

- Records checked: **${points.length}**.
- Core bilingual location/function/indication/needling fields complete: **${coreComplete ? "yes" : "no"}**.
- Existing content is not automatically source-checked merely because a field is non-empty.
- The visible "pending" experience now comes mainly from moxa specificity, proportional measurements, anatomy, exam pearls, clinical notes, evidence notes, and source traceability.

## Field Inventory

| Priority | Field | Present | Missing | Required source lane |
| --- | --- | ---: | ---: | --- |
${rows}

## Source Boundaries

1. **WHO / GB-T location lane:** point identity, standard location, anatomical landmarks, and proportional bone measurement only.
2. **Professional textbook safety lane:** point-specific depth, angle, moxibustion, contraindications, and nearby organ/vessel/nerve risk. General safety guidance cannot be copied into every point as if it were point-specific.
3. **Ting course-note lane:** NCCAOM high-yield flags, teacher-emphasized cautions, point comparisons, and common pairings. These remain private study drafts until reviewed.
4. **Evidence lane:** NCCIH, systematic reviews, and trials describe condition-level interventions. Do not turn a multi-point protocol result into a single-point efficacy claim.

## Recommended Batch Order

1. Close the **40 source-traceability gaps** with exact official or reviewed page references.
2. Extract WHO/GB-T **cun and landmark facts** into staging, then preview differences without overwriting existing locations.
3. Build an anatomy pilot for high-risk regions first: orbit, anterior neck, chest, upper back, abdomen, and sacral foramina.
4. Add point-specific moxa statements only where an approved textbook or course note gives an explicit statement; absence is not an indication.
5. Mine Ting's Notion notes for high-yield and pairing records using stable point codes and source-page IDs.
6. Keep modern evidence in condition-to-acupoint relationship records with uncertainty and study-design metadata.

## Gate

Do not write these gaps directly to \`data/acupoints/361.json\`. Each source batch must produce staging, a conflict report, and a field-level preview before Ting approves any canonical apply.
`;

fs.writeFileSync(MD_OUTPUT, markdown, "utf8");
console.log(JSON.stringify({ records: points.length, core_complete: coreComplete, findings: findings.map(({ field, missing_count }) => ({ field, missing_count })), canonical_writes: 0 }, null, 2));
