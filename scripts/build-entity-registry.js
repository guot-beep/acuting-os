#!/usr/bin/env node
/* V1-A of docs/ARCHITECTURE_MIGRATION_V1.md — the entity registry.

   Scans every record-bearing JSON file under data/ and emits
   data/generated/entity_registry.json: one row per referenceable entity,
   mapping its id to a type, bilingual names, its home file, and a collision
   report where the same concept lives under competing prefixes.

   READ-ONLY. This script changes no source data. It gives the app (and the
   later migration steps) a single place to resolve any id into a name — the
   thing the display layer has been faking with per-section special cases —
   and it produces the collision list V1-B needs.

   Usage:
     node scripts/build-entity-registry.js            # write the registry
     node scripts/build-entity-registry.js --report   # also print a summary
*/

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "data");
const REPORT = process.argv.includes("--report");

/* id prefix -> canonical entity type. Prefixes that are duplicates of another
   concept are mapped to the SAME type here and flagged as a collision, which
   is what V1-B will consolidate. */
const PREFIX_TYPE = {
  tung: "point", ear: "point", five_shu: "point-tag", influential: "point-tag",
  herb: "herb", pair: "herb-pair",
  formula: "formula", formula_category: "formula-category",
  cond: "condition", western_condition: "condition", xwalk: "condition-crosswalk",
  "cloudtcm": "condition-source",
  tdis: "condition", pattern: "pattern", pat: "pattern",
  move: "movement", cmp: "comparison-group", metric: "outcome-metric",
  med: "medication", learn: "learning", doc_req: "doc-requirement",
  system: "system", fertility: "workflow", cat: "taxonomy",
  _wf: "workflow-internal", ex: "point", visit: "clinical", patient_records: "clinical"
};

/* prefixes that are duplicates of a primary concept → the primary prefix */
const PREFIX_ALIAS_OF = {
  pat: "pattern",
  western_condition: "cond",
  xwalk: "cond"
};

const RECORD_KEYS = ["records", "herbs", "formulas", "points", "conditions",
  "entries", "items", "patterns", "pairs", "relations", "concepts", "groups",
  "movements", "sources"];

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === "node_modules" || e.name === ".git" || e.name === "generated") continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith(".json")) out.push(p);
  }
  return out;
}

function pickArray(json) {
  if (Array.isArray(json)) return json;
  for (const k of RECORD_KEYS) if (Array.isArray(json[k])) return json[k];
  const arrays = Object.values(json).filter(Array.isArray);
  return arrays.length ? arrays.sort((a, b) => b.length - a.length)[0] : null;
}

const registry = new Map();   // id -> entry
const collisions = [];        // {concept, prefixes}
const prefixCounts = {};
const nameIndex = new Map();   // name_en(lower) -> Set(prefix) — to spot cross-prefix dupes

function classify(id) {
  const prefix = String(id).includes(".") ? String(id).split(".")[0] : "(none)";
  return { prefix, type: PREFIX_TYPE[prefix] || "unclassified" };
}

for (const file of walk(DATA)) {
  const rel = path.relative(ROOT, file).replace(/\\/g, "/");
  let json;
  try { json = JSON.parse(fs.readFileSync(file, "utf8")); } catch { continue; }
  const arr = pickArray(json);
  if (!arr || !arr.length || typeof arr[0] !== "object") continue;

  for (const r of arr) {
    if (!r || typeof r.id !== "string" || !r.id) continue;
    const { prefix, type } = classify(r.id);
    prefixCounts[prefix] = (prefixCounts[prefix] || 0) + 1;

    const nameEn = r.name_en || r.label_en || "";
    if (nameEn) {
      const key = nameEn.toLowerCase().trim();
      if (!nameIndex.has(key)) nameIndex.set(key, new Set());
      nameIndex.get(key).add(prefix);
    }

    // first file wins as "home"; later files are recorded as also-appears-in
    if (registry.has(r.id)) {
      registry.get(r.id).also_in.push(rel);
      continue;
    }
    registry.set(r.id, {
      id: r.id,
      type,
      prefix,
      alias_of_prefix: PREFIX_ALIAS_OF[prefix] || null,
      name_zh: r.name_zh || r.label_zh || "",
      name_en: nameEn,
      pinyin: r.pinyin || r.pinyin_toned || "",
      home: rel,
      also_in: []
    });
  }
}

/* cross-prefix name collisions: same English name under >1 prefix = the same
   concept modelled twice. This is the V1-B worklist. */
for (const [name, prefixes] of nameIndex) {
  if (prefixes.size > 1) collisions.push({ name, prefixes: [...prefixes] });
}

const rows = [...registry.values()].sort((a, b) => a.id.localeCompare(b.id));
const dupHomes = rows.filter((r) => r.also_in.length);

const output = {
  _generated: "GENERATED by scripts/build-entity-registry.js — do not edit.",
  _purpose: "V1-A entity registry: resolve any id to its type, names and home file. Read-only snapshot.",
  built_at: new Date().toISOString(),
  entity_count: rows.length,
  prefix_counts: prefixCounts,
  duplicate_prefixes: PREFIX_ALIAS_OF,
  cross_prefix_name_collisions: collisions,
  entities_in_multiple_files: dupHomes.map((r) => ({ id: r.id, home: r.home, also_in: r.also_in })),
  entities: rows
};

const outPath = path.join(DATA, "generated", "entity_registry.json");
fs.writeFileSync(outPath, JSON.stringify(output, null, 2) + "\n", "utf8");
console.log(`entity registry: ${rows.length} entities → ${path.relative(ROOT, outPath).replace(/\\/g, "/")}`);

if (REPORT) {
  console.log("\n=== prefix counts ===");
  Object.entries(prefixCounts).sort((a, b) => b[1] - a[1])
    .forEach(([p, n]) => console.log(`  ${p.padEnd(20)} ${String(n).padStart(4)}  ${PREFIX_TYPE[p] || "unclassified"}${PREFIX_ALIAS_OF[p] ? "  → merges into " + PREFIX_ALIAS_OF[p] : ""}`));
  console.log(`\n=== ${collisions.length} cross-prefix name collisions (V1-B worklist) ===`);
  collisions.slice(0, 15).forEach((c) => console.log(`  "${c.name}"  in: ${c.prefixes.join(", ")}`));
  console.log(`\n=== ${dupHomes.length} ids appearing in more than one file ===`);
  dupHomes.slice(0, 12).forEach((r) => console.log(`  ${r.id}\n    home: ${r.home}\n    also: ${r.also_in.join(", ")}`));
}
